param(
    [string]$RustCompiler = 'rustc',
    [string]$ScriptRunner = 'oscript'
)

$ErrorActionPreference = 'Stop'
$utf8 = [Text.UTF8Encoding]::new($false)
$wasm = Join-Path ([IO.Path]::GetTempPath()) ('alt-web-' + [guid]::NewGuid() + '.wasm')
$oldEncoding = [Console]::OutputEncoding
$oldOutputEncoding = $OutputEncoding

try {
    [Console]::OutputEncoding = $utf8
    $OutputEncoding = $utf8
    $catalog = & $ScriptRunner (Join-Path $PSScriptRoot 'cases/forma/catalog.bsl')
    if ($LASTEXITCODE -ne 0) { throw 'Catalog generation failed.' }
    $catalogJson = $catalog -join [Environment]::NewLine
    $null = ConvertFrom-Json -InputObject $catalogJson

    & $RustCompiler --edition 2024 --target wasm32-unknown-unknown --crate-type cdylib -C opt-level=z -C strip=symbols -C panic=abort -o $wasm (Join-Path $PSScriptRoot 'site.rs')
    if ($LASTEXITCODE -ne 0) { throw 'Browser module compilation failed.' }

    # Embedding the module allows the demo to run directly from the filesystem.
    $base64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($wasm))
    $module = "// Generated by build.ps1.
'use strict';
const siteModule = new WebAssembly.Instance(new WebAssembly.Module(
  Uint8Array.from(atob('$base64'), (character) => character.charCodeAt(0))
)).exports;
"
    $catalogScript = "// Generated by build.ps1.
const catalog = $catalogJson;
"
    [IO.File]::WriteAllText((Join-Path $PSScriptRoot 'site-module.js'), $module, $utf8)
    [IO.File]::WriteAllText((Join-Path $PSScriptRoot 'cases/forma/catalog.js'), $catalogScript, $utf8)
} finally {
    [Console]::OutputEncoding = $oldEncoding
    $OutputEncoding = $oldOutputEncoding
    if (Test-Path -LiteralPath $wasm) { Remove-Item -LiteralPath $wasm }
}
